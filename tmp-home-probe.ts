
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import puppeteer from 'puppeteer';
import { resolveBrowserExecutable } from '/work/madarch/scripts/chromium.ts';
import { createDraft } from '/work/madarch/src/product/draft.ts';
import { startPreparedServer } from '/work/madarch/test/prepared-server.ts';
import { gitEnv } from '/work/madarch/test/git-env.ts';
import { SAMPLE_IDENTITY, commitProduct } from '/work/madarch/test/knowledge-fixture.ts';
const root=mkdtempSync(join(tmpdir(),'madarch-home-probe-'));
const draft=createDraft({home: join(root,'products'),name:'probe-home',gitEnv:gitEnv(SAMPLE_IDENTITY)});
if(draft.outcome!=='created') throw new Error(JSON.stringify(draft));
commitProduct(draft.folder,'probe');
const server=await startPreparedServer({productFolder:draft.folder,appFolder:'/work/madarch/wiki/app/dist',port:0,log:()=>undefined,errorLog:()=>undefined});
const browser=await puppeteer.launch({executablePath:resolveBrowserExecutable(),headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage(); const errors=[]; page.on('pageerror',e=>errors.push(String(e))); page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.evaluateOnNewDocument(()=>{try{localStorage.setItem('madarch-wiki-language','ru')}catch{}});
await page.goto(server.url+'/',{waitUntil:'domcontentloaded',timeout:60000});
await new Promise(r=>setTimeout(r,3000));
console.log('URL',page.url()); console.log('TEXT',(await page.evaluate(()=>document.body.textContent)).slice(0,2000)); console.log('ERR',errors.join('\n'));
await page.screenshot({path:'/work/shots/home-probe.png'});
await browser.close(); await server.stop(); rmSync(root,{recursive:true,force:true});
